async function main() {
  const [celCount, macCount] = await Promise.all([
    prisma.priceList.count({ where: { category: 'CELULAR' } }),
    prisma.priceList.count({ where: { category: 'MACIPAD' } }),
  ])
  if (celCount === 0) {
    await prisma.priceList.createMany({
      data: CELULARES.map((c, i) => ({
        category: 'CELULAR',
        modelo: c[0],
        almacenamiento: c[1],
        precioARS: c[2],
        preventaARS: c[3],
        descuentoARS: c[4],
        orden: i,
      })),
    })
    console.log(`Seeded ${CELULARES.length} celulares`)
  } else {
    console.log('CELULAR ya tiene datos, se saltea')
  }
  if (macCount === 0) {
    await prisma.priceList.createMany({
      data: MACIPAD.map((m, i) => ({
        category: 'MACIPAD',
        modelo: m[0],
        almacenamiento: m[1],
        precioARS: m[2],
        preventaARS: m[3],
        descuentoARS: m[4],
        orden: i,
      })),
    })
    console.log(`Seeded ${MACIPAD.length} Mac/iPad`)
  } else {
    console.log('MACIPAD ya tiene datos, se saltea')
  }

  const cuotasCount = await prisma.cuotasConfig.count()
  if (cuotasCount === 0) {
    await prisma.cuotasConfig.createMany({
      data: CUOTAS.map((c, i) => ({ cuotas: c.cuotas, coeficiente: c.coeficiente, activo: true, mostrar: true, orden: i })),
    })
    console.log(`Seeded ${CUOTAS.length} configuraciones de cuotas`)
  } else {
    console.log('CUOTAS ya tiene datos, se saltea')
  }

  const tomaCount = await prisma.priceTradeIn.count()
  if (tomaCount === 0) {
    await prisma.priceTradeIn.createMany({
      data: TOMA.map((t, i) => ({
        modelo: t[0],
        impecable: t[1],
        bateria: t[2],
        pantalla: t[3],
        camara: t[4],
        microfono: t[5],
        parlante: t[6],
        tapa: t[7],
        marco: t[8],
        pin: t[9],
        orden: i,
      })),
    })
    console.log(`Seeded ${TOMA.length} precios de toma`)
  } else {
    console.log('TOMA ya tiene datos, se saltea')
  }
}

